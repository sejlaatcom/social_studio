  function defaultTarget(score, levels) {
    levels = levels || LEVELS;
    if (score == null || isNaN(score)) return null;
    const asc = levels.slice().sort((a, b) => a.min - b.min);
    for (const l of asc) {
      if (l.min > score) return Math.min(100, Math.max(l.min + 2, Math.round(score + 5)));
    }
    return Math.min(100, Math.max(95, Math.round(score + 2)));
  }

